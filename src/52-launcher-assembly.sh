# ----------------------------------------------------- launcher assembly --

# Move a finished bundle into place. The old one is set aside, not deleted, and
# put back if the new one cannot be moved in. Both moves are renames inside one
# directory, so nothing is copied and nothing is half-written.
_swap_in() { # new bundle, destination, staging dir
  if [ -e "$2" ]; then
    # Set aside under a name no launcher can have (no .app), so a launcher
    # that happens to be called "previous" cannot be moved inside its own
    # replacement.
    SWAP_DST="$2"; SWAP_PREV="$3/.previous"
    mv "$2" "$SWAP_PREV" 2>/dev/null \
      || { SWAP_DST=""; SWAP_PREV=""; warn "Could not replace $2 (is it locked?). Nothing was changed."; return 1; }
    if ! mv "$1" "$2" 2>/dev/null; then
      if mv "$SWAP_PREV" "$2" 2>/dev/null; then
        SWAP_DST=""; SWAP_PREV=""
        warn "Could not move the new launcher into place. The old one is unchanged."
      else
        warn "Could not move the new launcher into place, nor put the old one back. It is at:
    $SWAP_PREV
    Move it back to: $2"
        # Keep the stage: it holds the only copy of the launcher.
        SWAP_DST=""; SWAP_PREV=""; BUILD_STAGE=""
      fi
      return 1
    fi
    SWAP_DST=""; SWAP_PREV=""
  else
    mv "$1" "$2" 2>/dev/null || { warn "Could not create $2"; return 1; }
  fi
  return 0
}

_assemble_launcher() { # out, src_app, profile, data_dir, label, letter, hex, kind, extras
  local dst="$1" src_app="$2" profile="$3" data_dir="$4" label="$5" letter="$6" hex="$7" kind="$8"
  local extras="${9:-}" env_q="" args_q="" v exe_re=""
  # A pattern for any running copy of the app: its main executable, at the
  # start of the command line. Regex characters in the path are escaped.
  v=$(app_exe "$src_app") && exe_re="^$(printf '%s' "$v" | sed 's/[][\.*^$+?(){}|]/\\&/g')( |\$)"
  while IFS= read -r v; do [ -n "$v" ] && env_q="$env_q --env $(shquote "$v")"; done <<EOF
$(extras_lines env "$extras")
EOF
  while IFS= read -r v; do [ -n "$v" ] && args_q="$args_q $(shquote "$v")"; done <<EOF
$(extras_lines arg "$extras")
EOF
  if [ -n "$(extras_lines ext "$extras")" ]; then
    args_q="$args_q --extensions-dir=$(shquote "$data_dir/extensions")"
  fi

  mkdir -p "$dst/Contents/MacOS" "$dst/Contents/Resources" 2>/dev/null \
    || { warn "Could not create $dst"; return 1; }

  # The launcher is a plain shell script in a plain bundle. Every value it
  # carries is written with shquote, and the one AppleScript (the sign-in
  # guard) takes its words as arguments, never pasted into its source. -n
  # starts a new instance even
  # when the app is already running. For a main launcher that is the whole
  # point: Launch Services sees every profile as the same app, so opening the
  # app itself only switches to whichever profile is already running.
  {
    printf '#!/bin/sh\n'
    printf '# Generated by aidentity %s. Safe to delete.\n' "$AIDENTITY_VERSION"
    # `open` hands its own environment to the app, so a profile opened from a
    # terminal inherited NODE_OPTIONS, ELECTRON_* or VSCODE_* (which overrides
    # --extensions-dir). Drop those before opening. Names are read in the C
    # locale: under UTF-8, sed stops at the first value that is not valid text.
    cat <<'SCRUB'
set --
for name in $(/usr/bin/env | LC_ALL=C /usr/bin/sed -n 's/^\([A-Za-z_][A-Za-z0-9_]*\)=.*/\1/p'); do
  case "$name" in DYLD_*|LD_*|ELECTRON_*|NODE_*|VSCODE_*|CHROME_*|CHROMIUM_*|SSLKEYLOGFILE) set -- "$@" -u "$name" ;; esac
done
SCRUB
    if [ "$kind" != "main" ] && [ -n "$exe_re" ]; then
      # The sign-in guard. With several copies of one app running, macOS hands
      # an opened link to the copy that started first, and a browser sign-in
      # comes back as such a link. On a new profile's first open, while another
      # copy runs, say so once and offer to cancel. It only warns: if the
      # dialog cannot be shown, the profile opens anyway.
      printf 'data=%s\n' "$(shquote "$data_dir")"
      printf 'running=%s\n' "$(shquote "$exe_re")"
      printf 'label=%s\n' "$(shquote "$label")"
      printf 'name=%s\n' "$(shquote "$(bundle_name "$src_app")")"
      cat <<'GUARD'
if [ ! -e "$data/Local State" ] && [ ! -e "$data/Preferences" ] && [ ! -e "$data/Cookies" ] \
   && [ ! -d "$data/Default" ] && /usr/bin/pgrep -qf -U "$(/usr/bin/id -u)" "$running"; then
  answer=$(/usr/bin/osascript - "$label" "$name" 2>/dev/null <<'OSA'
on run argv
	set l to item 1 of argv
	set a to item 2 of argv
	try
		display dialog "Opening " & l & " for the first time." & return & return & "Another " & a & " is already open. If " & a & " signs you in through your browser, macOS returns the sign-in to the " & a & " that started first, not to this one." & return & return & "To be safe, quit the other " & a & " windows, sign in here, then open them again." buttons {"Cancel", "Open Anyway"} default button "Open Anyway" with title "aidentity" with icon caution
	on error number -128
		return "cancel"
	end try
	return "open"
end run
OSA
)
  [ "$answer" = "cancel" ] && exit 0
fi
GUARD
    fi
    if [ "$kind" = "main" ]; then
      printf 'exec /usr/bin/env "$@" /usr/bin/open -na %s%s%s\n' \
        "$(shquote "$src_app")" "$env_q" "${args_q:+ --args$args_q}"
    else
      printf 'exec /usr/bin/env "$@" /usr/bin/open -na %s%s --args --user-data-dir=%s%s\n' \
        "$(shquote "$src_app")" "$env_q" "$(shquote "$data_dir")" "$args_q"
    fi
  } > "$dst/Contents/MacOS/launcher" || { warn "Could not write the launcher script."; return 1; }
  chmod +x "$dst/Contents/MacOS/launcher"

  local bid
  bid="com.aidentity.$(slugify "$label")"

  local x_label x_profile x_src x_data
  x_label=$(xmlescape "$label")
  x_profile=$(xmlescape "$profile")
  x_src=$(xmlescape "$src_app")
  x_data=$(xmlescape "$data_dir")
  # Recorded so `set` and `rebuild` can regenerate the icon without asking the
  # user to remember what they picked. An empty badge means "no badge".
  local x_badge; x_badge=$(xmlescape "$letter")
  local x_main=""
  [ "$kind" = "main" ] && x_main="<key>AIdentityMain</key><true/>"

  cat > "$dst/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleName</key><string>$x_label</string>
	<key>CFBundleDisplayName</key><string>$x_label</string>
	<key>CFBundleIdentifier</key><string>$bid</string>
	<key>CFBundleExecutable</key><string>launcher</string>
	<key>CFBundlePackageType</key><string>APPL</string>
	<key>CFBundleShortVersionString</key><string>$AIDENTITY_VERSION</string>
	<key>CFBundleVersion</key><string>$AIDENTITY_VERSION</string>
	<key>CFBundleIconFile</key><string>icon</string>
	<key>LSUIElement</key><true/>
	<key>$MARKER_KEY</key><string>$x_profile</string>
	<key>AIdentityTargetApp</key><string>$x_src</string>
	<key>AIdentityDataDir</key><string>$x_data</string>
	<key>AIdentityBadge</key><string>$x_badge</string>
	<key>AIdentityColor</key><string>$hex</string>
	$(extras_plist_xml "$extras")
	$x_main
</dict>
</plist>
PLIST

  # Never ship this. A bundle whose plist cannot be parsed is invisible to
  # is_our_launcher, which made it unremovable by rm and un-overwritable by add.
  # The staging directory is discarded, so nothing on disk changes.
  if ! plutil -lint "$dst/Contents/Info.plist" >/dev/null 2>&1; then
    warn "Generated a malformed Info.plist for '$label' — nothing was changed."
    return 1
  fi

  # An empty letter means the user asked for the app's own icon, untouched.
  local have_icon=1
  if [ -z "$letter" ]; then
    copy_plain_icon "$src_app" "$dst/Contents/Resources/icon.icns" || have_icon=0
  elif build_icon "$src_app" "$letter" "$hex" "$dst/Contents/Resources/icon.icns"; then
    :
  elif copy_plain_icon "$src_app" "$dst/Contents/Resources/icon.icns"; then
    warn "Could not badge the icon; using the app's own icon instead."
  else
    have_icon=0
  fi

  # Declaring an icon that is not there gives a broken-looking bundle. Drop the
  # key instead and say so, rather than claiming an icon we failed to write.
  if [ "$have_icon" -eq 0 ]; then
    /usr/libexec/PlistBuddy -c "Delete :CFBundleIconFile" "$dst/Contents/Info.plist" >/dev/null 2>&1 || true
    warn "$(bundle_name "$src_app") has no icon to copy; the launcher uses the default one."
  fi

  # Ad-hoc sign so the bundle is internally consistent. Not required to launch a
  # locally-built app, so a missing toolchain is a note, not an error.
  if command -v codesign >/dev/null 2>&1 && xcode-select -p >/dev/null 2>&1; then
    codesign --force --sign - "$dst" >/dev/null 2>&1 \
      || warn "Could not sign $label.app. It will still launch."
  fi
  # A proxy setting can carry a password: a launcher with settings is readable
  # by its owner only.
  if [ -n "$extras" ]; then
    chmod 600 "$dst/Contents/Info.plist" && chmod 700 "$dst/Contents/MacOS/launcher" \
      || { warn "Could not make $label.app owner-only."; return 1; }
  fi
  return 0
}
